    def step_kernel_patches(self) -> tuple[str, str]:
        repo = self.clone_or_update(KERNEL_PATCHES_REPO, WORK_DIR / "ps5-linux-patches")

        build_sh = repo / KERNEL_BUILD_SCRIPT
        if build_sh.is_file() and (repo / "build.cfg").is_file():
            return self._run_kernel_build(repo, build_sh)

        script = self.find_script(repo, KERNEL_SCRIPT_NAMES)
        if script:
            self.info(f"Found {script.relative_to(repo)}; running it as root.")
            self.run_repo_script(script)
            return "ok", f"ran {script.relative_to(repo)}"

        patches = sorted(
            p for p in [*repo.rglob("*.patch"), *repo.rglob("*.diff")]
            if ".git" not in p.relative_to(repo).parts
        )
        self.warn("No install.sh or apply.sh found - the patches must be applied manually.")
        readmes = [p for p in repo.iterdir() if p.name.lower().startswith("readme")]
        for readme in readmes:
            self.info(f"Read the repository notes first: {readme}")
        if patches:
            self.info(f"{len(patches)} patch file(s) found:")
            for patch in patches[:40]:
                self.info(f"    {patch.relative_to(repo)}")
            if len(patches) > 40:
                self.info(f"    ... and {len(patches) - 40} more")
        else:
            self.warn("No *.patch / *.diff files found either; see the README.")

        patch_glob = shlex.quote(str(repo)) + "/*.patch"
        for line in (
            "Manual application:",
            "  1. Install build dependencies:",
            "       sudo apt install build-essential bc bison flex libssl-dev libelf-dev dwarves git",
            "  2. Fetch the kernel source version the patches target (see README), e.g.:",
            "       git clone --depth 1 --branch vX.Y "
            "https://git.kernel.org/pub/scm/linux/kernel/git/stable/linux.git",
            "  3. Apply the patches inside the kernel tree:",
            f"       cd linux && for p in {patch_glob}; do patch -p1 < \"$p\" || break; done",
            f"     (or, for git-formatted patches:  git am {patch_glob})",
            "  4. Build Debian packages:",
            "       make olddefconfig && make -j\"$(nproc)\" bindeb-pkg",
            "  5. Install and reboot:",
            "       sudo dpkg -i ../linux-image-*.deb ../linux-headers-*.deb && sudo reboot",
        ):
            self.info(line)
        return "manual", "no install script - follow the manual steps in the log"

    def _run_kernel_build(self, repo: Path, build_sh: Path) -> tuple[str, str]:
        if not self.opts.efi_dir:
            raise StepError("no boot partition selected")

        self.info("Installing kernel build dependencies.")
        self.apt_install(KERNEL_BUILD_DEPS)

        cfg = WORK_DIR / "kernel-build.cfg"
        base = (repo / "build.cfg").read_text()
        extra = (f"\n\n# Added by {APP_NAME}: boot partition chosen in the wizard,"
                 " so build.sh does not stop to ask.\n"
                 f"EFI_DIR={shlex.quote(self.opts.efi_dir)}\n")
        if self.opts.wifi:
            extra += ("\n# Added by the wizard: experimental MediaTek MT7921 WiFi driver.\n"
                      'CONFIG_OPS+=("--module MT7921E")\n')
            self.warn("Including the EXPERIMENTAL MediaTek mt7921e driver in the kernel "
                      "(very unstable, crashes often).")
        cfg.write_text(base.rstrip("\n") + extra)
        self.info(f"Build config: {cfg} (repository build.cfg + EFI_DIR={self.opts.efi_dir})")
        self.warn("Building the kernel takes a long time (full LTO by default). "
                  "Keep the PS5 powered and connected.")

        self.run_repo_script(build_sh, args=[str(cfg)])
        if self.opts.wifi:
            self._write_mt7921e_options()
        return "ok", f"kernel built and deployed to {self.opts.efi_dir} (cold boot to use it)"

    def step_wifi(self) -> tuple[str, str]:
        self.warn("EXPERIMENTAL: the MediaTek mt7921e driver is very unstable on the PS5 "
                  "and crashes often.")
        devices = detect_mediatek_devices()
        if devices is None:
            self.warn("lspci is unavailable; cannot detect the WiFi card.")
            devices = []
        for line in devices:
            self.ok(f"Detected: {describe_mediatek_device(line)}")
            self.info(f"    {line}")
            if MEDIATEK_PCI_RE.search(line).group(1).lower() != "7961":
                self.warn("    The driver is only tested with the MT7921 (14c3:7961).")

        if not devices:
            if not self.opts.wifi_force:
                self.warn("No MediaTek (14c3) PCI device found and force install is off.")
                return "skipped", "no MediaTek card detected"
            self.warn("No MediaTek card detected, installing anyway (forced).")

        release = os.uname().release
        if self.capture(["modinfo", "-F", "filename", "mt7921e"]).strip():
            self.info(f"mt7921e is already available for kernel {release}.")
            self._write_mt7921e_options()
            if Path("/sys/module/mt7921e").exists():
                return "ok", "configured mt7921e; reboot so disable_aspm=1 takes effect"
            self.run_cmd(["modprobe", "-v", "mt7921e"])
            return "ok", "configured and loaded mt7921e"

        kdir = self._find_kernel_tree(release)
        if kdir is None:
            raise StepError(
                f"no build tree with sources for kernel {release} (Module.symvers and "
                "drivers/net/wireless/mediatek/mt76). Run kernel patching with the "
                "MediaTek option ticked, then cold boot."
            )
        mt76 = kdir / "drivers/net/wireless/mediatek/mt76"
        self.info(f"Building mt7921e for {release} from {kdir}.")

        deps = list(WIFI_BUILD_DEPS)
        kconfig = (kdir / ".config").read_text(errors="replace") if (kdir / ".config").is_file() else ""
        clang = re.search(r"^CONFIG_CLANG_VERSION=(\d+)$", kconfig, re.MULTILINE)
        if clang and int(clang.group(1)):
            major = int(clang.group(1)) // 10000
            versioned = [f"clang-{major}", f"lld-{major}", f"llvm-{major}"]
            deps += versioned if self.apt_has_candidate(versioned[0]) else ["clang", "lld", "llvm"]
        self.apt_install(deps)

        repo = self.clone_or_update(WIFI_DRIVER_REPO, WORK_DIR / "ps5-mt7921-wifi")
        install_py = repo / "install.py"
        if not install_py.is_file():
            self.warn("install.py not found in the WiFi repository.")
            self.info(f"See the README in {repo}.")
            return "manual", "no install script - see the repository README"

        self.run_cmd(["python3", str(install_py), "--build"], cwd=repo,
                     env_extra={"KDIR": str(kdir), "MT76_SRC": str(mt76)})
        self._write_mt7921e_options()
        return "ok", f"built and installed mt7921e for {release} (disable_aspm=1)"

    @staticmethod
    def _find_kernel_tree(release: str) -> Path | None:
        for tree in (Path(f"/lib/modules/{release}/build"), WORK_DIR / "linux"):
            if not (tree / "Module.symvers").is_file():
                continue
            if not (tree / "drivers/net/wireless/mediatek/mt76/mt7921/pci.c").is_file():
                continue
            built = tree / "include/config/kernel.release"
            if built.is_file() and built.read_text().strip() != release:
                continue
            return tree.resolve()
        return None

    def step_steam_install(self) -> tuple[str, str]:
        osr = read_os_release()
        ids = {osr.get("ID", "")} | set(osr.get("ID_LIKE", "").split())
        is_ubuntu = "ubuntu" in ids
        self.info(f"Distribution: {osr.get('PRETTY_NAME', 'unknown')}")

        if "i386" not in self.capture(["dpkg", "--print-foreign-architectures"]).split():
            self.run_cmd(["dpkg", "--add-architecture", "i386"])
            self._apt_updated = False

        if is_ubuntu:
            if not shutil.which("add-apt-repository", path=SAFE_PATH):
                self.apt_install(["software-properties-common"], check=False)
            self.run_cmd(["add-apt-repository", "-y", "multiverse"], check=False)
            self._apt_updated = False

        self.apt_update()

        self.run_cmd(
            ["debconf-set-selections"],
            input_text="steam steam/question select I AGREE\nsteam steam/license note \n",
            check=False,
        )

        steam_pkg = next((p for p in ("steam-installer", "steam") if self.apt_has_candidate(p)), None)
        if steam_pkg:
            self.apt_install([steam_pkg])
            installed = steam_pkg
        else:
            hint = ("enable the 'contrib' component in /etc/apt/sources.list"
                    if not is_ubuntu else "enable the 'multiverse' component")
            self.warn(f"No Steam package in apt (to use the distro package, {hint}).")
            self.info(f"Falling back to Valve's installer: {STEAM_DEB_URL}")
            deb = WORK_DIR / "steam.deb"
            self._download(STEAM_DEB_URL, deb)
            self.apt_install([str(deb)])
            installed = "steam.deb (Valve)"

        self.apt_install(
            ["mesa-vulkan-drivers", "mesa-vulkan-drivers:i386",
             "libgl1-mesa-dri:i386", "libglx-mesa0:i386"],
            check=False,
        )

        if self.apt_has_candidate("gamescope"):
            self.apt_install(["gamescope"])
            installed += ", gamescope"
        else:
            self.warn("gamescope is not available in your apt sources (it ships with "
                      "Ubuntu 23.04+ and Debian 13+). Build it from "
                      "https://github.com/ValveSoftware/gamescope or skip the gamescope option.")

        return "ok", f"installed {installed}"

    def _download(self, url: str, dest: Path) -> None:
        self.info(f"Downloading {url}")
        try:
            with urllib.request.urlopen(url, timeout=60) as resp, dest.open("wb") as out:
                while chunk := resp.read(1 << 16):
                    self._check_cancel()
                    out.write(chunk)
        except Cancelled:
            dest.unlink(missing_ok=True)
            raise
        except OSError as exc:
            dest.unlink(missing_ok=True)
            raise StepError(f"download failed: {exc}") from exc
        self.ok(f"Saved {dest} ({dest.stat().st_size // 1024} KiB)")

