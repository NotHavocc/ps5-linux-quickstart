    def step_autostart(self) -> tuple[str, str]:
        user = self.opts.user
        if user.pw_uid == 0:
            self.warn("Could not determine a non-root desktop user; writing to root's home.")
        autostart_dir = Path(user.pw_dir) / ".config" / "autostart"
        target = autostart_dir / "steam.desktop"

        if self.opts.gaming_mode or gaming_mode_installed():
            removed = self._remove_desktop_steam_autostart()
            return "skipped", ("Gaming Mode is set up, so Steam does not autostart on the desktop"
                               + ("; removed the existing entry" if removed else ""))

        if self.opts.gamepad_ui:
            exec_line = str(GAMEPADUI_LAUNCHER)
            name = "Steam (Deck UI)"
        else:
            exec_line = find_steam_binary() or "/usr/games/steam"
            name = "Steam"
            if not find_steam_binary():
                self.warn("Steam is not installed yet; the autostart entry will work once it is.")

        try:
            self.make_user_dirs(autostart_dir)
        except OSError as exc:
            raise StepError(f"could not create {autostart_dir}: {exc}") from exc

        if target.exists():
            backup = target.with_name(f"steam.desktop.bak.{datetime.datetime.now():%Y%m%d-%H%M%S}")
            shutil.copy2(target, backup)
            os.chown(backup, user.pw_uid, user.pw_gid)
            self.info(f"Backed up existing entry to {backup}")

        self.write_file(
            target,
            DESKTOP_TEMPLATE.format(
                name=name,
                comment=f"Started on login by {APP_NAME}",
                exec=exec_line,
                extra="X-GNOME-Autostart-enabled=true\n"
                      "X-GNOME-Autostart-Delay=5\n"
                      "X-KDE-autostart-after=panel\n",
            ),
            0o644,
            owned_by_user=True,
        )
        return "ok", f"{target} -> {exec_line}"

    def step_dualsense(self) -> tuple[str, str]:
        self.apt_install(["bluez"])
        if self.apt_has_candidate("steam-devices"):
            self.apt_install(["steam-devices"], check=False)

