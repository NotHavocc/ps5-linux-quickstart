def _display_environment() -> list[str]:
    env: dict[str, str] = {"PS5_SETUP_USER": pwd.getpwuid(os.getuid()).pw_name}
    for var in ("XDG_CURRENT_DESKTOP", "XDG_SESSION_TYPE"):
        if os.environ.get(var):
            env[var] = os.environ[var]

    display = os.environ.get("DISPLAY")
    if display:
        env["DISPLAY"] = display
        xauth = os.environ.get("XAUTHORITY") or str(Path.home() / ".Xauthority")
        if Path(xauth).exists():
            env["XAUTHORITY"] = xauth

    wayland = os.environ.get("WAYLAND_DISPLAY")
    runtime_dir = os.environ.get("XDG_RUNTIME_DIR")
    if wayland:
        if not wayland.startswith("/") and runtime_dir:
            wayland = os.path.join(runtime_dir, wayland)
        env["WAYLAND_DISPLAY"] = wayland
        env["QT_QPA_PLATFORM"] = os.environ.get("QT_QPA_PLATFORM", "wayland;xcb")
    elif "QT_QPA_PLATFORM" in os.environ:
        env["QT_QPA_PLATFORM"] = os.environ["QT_QPA_PLATFORM"]

    return [f"{key}={value}" for key, value in env.items()]


def build_elevation_command() -> list[str] | None:
    self_cmd = [sys.executable, os.path.abspath(sys.argv[0]), *sys.argv[1:]]
    env_args = ["env", *_display_environment()]

    if shutil.which("pkexec"):
        return ["pkexec", *env_args, *self_cmd]
    if shutil.which("sudo"):
        if os.environ.get("SUDO_ASKPASS"):
            return ["sudo", "-A", *env_args, *self_cmd]
        if sys.stdin is not None and sys.stdin.isatty():
            return ["sudo", *env_args, *self_cmd]
    return None


def relaunch_as_root() -> int:
    cmd = build_elevation_command()
    if cmd is None:
        QMessageBox.critical(
            None,
            APP_NAME,
            "This setup needs root privileges, but neither pkexec nor an "
            "interactive sudo is available.\n\n"
            "Run it from a terminal instead:\n"
            f"  sudo python3 {shlex.quote(os.path.abspath(sys.argv[0]))}",
        )
        return 1

    print(f"[{APP_NAME}] Requesting root privileges via {cmd[0]}...", file=sys.stderr)
    try:
        rc = subprocess.call(cmd)
    except OSError as exc:
        QMessageBox.critical(None, APP_NAME, f"Failed to start {cmd[0]}: {exc}")
        return 1

    if cmd[0] == "pkexec" and rc in (126, 127):
        QMessageBox.warning(
            None,
            APP_NAME,
            "Authentication was cancelled or failed, so the setup cannot run.",
        )
    return rc


