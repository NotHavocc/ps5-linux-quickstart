def is_root() -> bool:
    return os.geteuid() == 0


def resolve_target_user() -> pwd.struct_passwd:
    for var in ("PS5_SETUP_USER", "SUDO_USER"):
        name = os.environ.get(var)
        if name and name != "root":
            try:
                return pwd.getpwnam(name)
            except KeyError:
                pass
    uid = os.environ.get("PKEXEC_UID")
    if uid and uid.isdigit() and int(uid) != 0:
        try:
            return pwd.getpwuid(int(uid))
        except KeyError:
            pass
    return pwd.getpwuid(os.getuid())


def read_os_release() -> dict[str, str]:
    data: dict[str, str] = {}
    for candidate in ("/etc/os-release", "/usr/lib/os-release"):
        try:
            text = Path(candidate).read_text()
        except OSError:
            continue
        for line in text.splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                key, value = line.split("=", 1)
                data[key.strip()] = value.strip().strip("\"'")
        break
    return data


def detect_mediatek_devices() -> list[str] | None:
    lspci = shutil.which("lspci", path=SAFE_PATH)
    if not lspci:
        return None
    try:
        out = subprocess.run(
            [lspci, "-nn"], capture_output=True, text=True, timeout=15
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return None
    return [line for line in out.splitlines() if MEDIATEK_PCI_RE.search(line)]


def describe_mediatek_device(line: str) -> str:
    match = MEDIATEK_PCI_RE.search(line)
    device_id = match.group(1).lower() if match else ""
    model = MT7921E_DEVICES.get(device_id)
    return f"{model} (14c3:{device_id})" if model else f"unknown MediaTek device (14c3:{device_id})"


def find_boot_partitions() -> list[str]:
    found: list[str] = []
    try:
        mounts = Path("/proc/mounts").read_text().splitlines()
    except OSError:
        return found
    for line in mounts:
        fields = line.split()
        if len(fields) < 2 or not fields[0].startswith("/dev/"):
            continue
        mnt = re.sub(r"\\([0-7]{3})", lambda m: chr(int(m.group(1), 8)), fields[1])
        if mnt not in found and os.path.isfile(os.path.join(mnt, "bzImage")):
            found.append(mnt)
    return found


