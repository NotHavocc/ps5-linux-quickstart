    def step_gaming_mode(self) -> tuple[str, str]:
        user = self.opts.user
        if user.pw_uid == 0:
            raise StepError("could not determine the desktop user; start the wizard "
                            "from your normal desktop account")
        if not shutil.which("gamescope", path=SAFE_PATH):
            raise StepError("gamescope is not installed; tick 'Install Steam and gamescope' "
                            "or install it first")
        steam = find_steam_binary()
        if not steam:
            raise StepError("Steam is not installed; tick 'Install Steam and gamescope' "
                            "or install it first")
        if not GDM_CUSTOM_CONF.parent.is_dir():
            raise StepError(f"{GDM_CUSTOM_CONF.parent} not found; switching sessions needs "
                            "GDM, Ubuntu's standard login screen")
        if not shutil.which("sudo", path=SAFE_PATH):
            self.apt_install(["sudo"])

        targets = [GAMEMODE_SESSION_SCRIPT, GAMEMODE_SESSION_FILE, SESSION_SWITCH_HELPER,
                   STEAMOS_SESSION_SELECT, RETURN_TO_GAMING_ENTRY, GAMEMODE_CONF,
                   GAMEMODE_BOOT_UNIT, *STEAMOS_STUBS]
        for path in targets:
            if path.exists() and GENERATED_MARKER not in path.read_text(errors="replace"):
                raise StepError(f"{path} already exists and was not created by {APP_NAME}; "
                                "remove it or the package that provides it first")

        account = self._accounts_user_path(user.pw_uid)
        desktop_session = self._desktop_session_name(account)
        self.info(f"Desktop session: {desktop_session}; Gaming Mode session: "
                  f"{GAMEMODE_SESSION_NAME}.")

        self.write_generated_file(GAMEMODE_SESSION_SCRIPT, GAMEMODE_SESSION_TEMPLATE.format(
            marker=GENERATED_MARKER, width=self.opts.gamescope_width,
            height=self.opts.gamescope_height,
        ), 0o755)
        self.write_generated_file(GAMEMODE_SESSION_FILE, GAMEMODE_SESSION_ENTRY.format(
            marker=GENERATED_MARKER, script=GAMEMODE_SESSION_SCRIPT,
        ), 0o644)

        self.write_generated_file(SESSION_SWITCH_HELPER, SESSION_SWITCH_TEMPLATE.format(
            marker=GENERATED_MARKER, user=user.pw_name, uid=user.pw_uid,
            account=shlex.quote(account), sudoers=SESSION_SWITCH_SUDOERS,
            gaming=shlex.quote(GAMEMODE_SESSION_NAME), desktop=shlex.quote(desktop_session),
            helper=SESSION_SWITCH_HELPER, boot_unit=GAMEMODE_BOOT_UNIT.name,
        ), 0o755)
        self.write_generated_file(STEAMOS_SESSION_SELECT, SESSION_SELECT_TEMPLATE.format(
            marker=GENERATED_MARKER, helper=SESSION_SWITCH_HELPER,
        ), 0o755)
        for stub, body in STEAMOS_STUBS.items():
            self.write_generated_file(stub, f"#!/bin/sh\n# {GENERATED_MARKER}: stub for a "
                                            f"SteamOS command Steam calls in Gaming Mode.\n{body}\n",
                                      0o755)
        return_entry = RETURN_TO_GAMING_TEMPLATE.format(
            marker=GENERATED_MARKER, select=STEAMOS_SESSION_SELECT,
        )
        self.write_generated_file(RETURN_TO_GAMING_ENTRY, return_entry, 0o644)
        self._add_desktop_shortcut(RETURN_TO_GAMING_ENTRY.name, return_entry)

        self.install_sudoers_rule(
            SESSION_SWITCH_SUDOERS,
            f"{user.pw_name} ALL=(root) NOPASSWD: {SESSION_SWITCH_HELPER} gamescope, "
            f"{SESSION_SWITCH_HELPER} desktop\n",
        )
        if self.run_cmd(["runuser", "-u", user.pw_name, "--", "sudo", "-n", "-l",
                         str(SESSION_SWITCH_HELPER), "desktop"], check=False) != 0:
            raise StepError("sudo did not pick up the session-switch rule; is "
                            "'@includedir /etc/sudoers.d' in /etc/sudoers?")

        self.write_generated_file(GAMEMODE_CONF, (
            f"# {GENERATED_MARKER}.\nUSER={user.pw_name}\n"
            f"DESKTOP_SESSION={desktop_session}\nGAMING_SESSION={GAMEMODE_SESSION_NAME}\n"
        ), 0o644)

        self._enable_gdm_autologin(user.pw_name)

        self._remove_desktop_steam_autostart()

        first = GAMEMODE_SESSION_NAME if self.opts.boot_to_gaming else desktop_session
        self._set_account_session(account, first)
        if self.opts.boot_to_gaming:
            self.write_generated_file(GAMEMODE_BOOT_UNIT, GAMEMODE_BOOT_UNIT_TEMPLATE.format(
                marker=GENERATED_MARKER, helper=SESSION_SWITCH_HELPER,
            ), 0o644)
            self.run_cmd(["systemctl", "daemon-reload"], check=False)
            self.run_cmd(["systemctl", "enable", GAMEMODE_BOOT_UNIT.name])
            where = "Gaming Mode on every boot"
        else:
            if GAMEMODE_BOOT_UNIT.exists():
                self.run_cmd(["systemctl", "disable", GAMEMODE_BOOT_UNIT.name], check=False)
                GAMEMODE_BOOT_UNIT.unlink()
                self.run_cmd(["systemctl", "daemon-reload"], check=False)
                self.info(f"Removed {GAMEMODE_BOOT_UNIT}: boots now keep the last session.")
            where = "the last session used (desktop for now)"
        return "ok", f"installed; the PS5 logs {user.pw_name} into {where} automatically"

    def _add_desktop_shortcut(self, name: str, content: str) -> None:
        user = self.opts.user
        home = Path(user.pw_dir).resolve()
        out = self.capture(self.user_cmd(["xdg-user-dir", "DESKTOP"])).strip()
        desktop = Path(out) if out else home / "Desktop"
        if not desktop.is_absolute() or home not in desktop.resolve().parents:
            desktop = home / "Desktop"
        target = desktop / name
        try:
            if target.is_symlink() or (target.exists() and GENERATED_MARKER
                                       not in target.read_text(errors="replace")):
                self.warn(f"{target} exists and was not created by {APP_NAME}; leaving it.")
                return
            self.make_user_dirs(desktop)
            self.write_file(target, content, 0o755, owned_by_user=True)
        except (OSError, StepError) as exc:
            self.warn(f"Could not put the shortcut on the desktop: {exc}")
            return
        self.run_cmd(self.user_cmd(["gio", "set", str(target), "metadata::trusted", "true"],
                                   session_bus=True), check=False)

    def _accounts_user_path(self, uid: int) -> str:
        out = self.capture(["busctl", "call", "org.freedesktop.Accounts",
                            "/org/freedesktop/Accounts", "org.freedesktop.Accounts",
                            "FindUserById", "x", str(uid)])
        match = re.search(r'o "([^"]+)"', out)
        if not match:
            raise StepError("AccountsService is not available; GDM needs it to pick the session")
        return match.group(1)

    def _desktop_session_name(self, account: str) -> str:
        out = self.capture(["busctl", "get-property", "org.freedesktop.Accounts", account,
                            "org.freedesktop.Accounts.User", "Session"]).strip()
        match = re.fullmatch(r's "(.*)"', out)
        candidates = [match.group(1) if match else ""]
        if GAMEMODE_CONF.is_file():
            saved = re.search(r"^DESKTOP_SESSION=(.*)$", GAMEMODE_CONF.read_text(), re.MULTILINE)
            candidates.append(saved.group(1).strip() if saved else "")
        candidates += [name for name in ("ubuntu", "gnome")
                       if Path(f"/usr/share/wayland-sessions/{name}.desktop").is_file()]
        for name in candidates:
            if name and name != GAMEMODE_SESSION_NAME and SESSION_NAME_RE.fullmatch(name):
                return name
        raise StepError("could not find the desktop session to switch back to")

    def _set_account_session(self, account: str, session: str) -> None:
        base = ["busctl", "call", "org.freedesktop.Accounts", account,
                "org.freedesktop.Accounts.User"]
        self.run_cmd(base + ["SetSession", "s", session])
        self.run_cmd(base + ["SetSessionType", "s", "wayland"], check=False)

    def _enable_gdm_autologin(self, username: str) -> None:
        try:
            text = GDM_CUSTOM_CONF.read_text() if GDM_CUSTOM_CONF.exists() else ""
            new = set_gdm_autologin(text, username)
            if new == text:
                self.info("GDM automatic login is already on.")
                return
            backup = GDM_CUSTOM_CONF.with_name(GDM_CUSTOM_CONF.name + ".ps5-quickstart.bak")
            if GDM_CUSTOM_CONF.exists() and not backup.exists():
                shutil.copy2(GDM_CUSTOM_CONF, backup)
                self.info(f"Backed up {GDM_CUSTOM_CONF} to {backup}")
            GDM_CUSTOM_CONF.write_text(new)
        except OSError as exc:
            raise StepError(f"could not update {GDM_CUSTOM_CONF}: {exc}") from exc
        self.warn(f"Automatic login enabled for {username} (no password at boot).")
        if re.search(r"^\s*WaylandEnable\s*=\s*false", new, re.MULTILINE | re.IGNORECASE):
            self.warn("WaylandEnable=false is set in custom.conf; GDM will not offer the "
                      "Gaming Mode session until it is removed.")

    def step_live_wallpaper(self) -> tuple[str, str]:
        user = self.opts.user
        if user.pw_uid == 0:
            raise StepError("could not determine the desktop user; start the wizard "
                            "from your normal desktop account")
        source = Path(self.opts.wallpaper_file)
        if not source.is_file():
            raise StepError(f"wallpaper video not found: {source}")

        version_out = self.capture(["gnome-shell", "--version"])
        match = re.search(r"GNOME Shell (\d+)", version_out)
        if not match:
            raise StepError("GNOME Shell not found; the live wallpaper needs the stock "
                            "Ubuntu (GNOME) desktop")
        gnome = int(match.group(1))
        if gnome < HANABI_MIN_GNOME:
            raise StepError(f"GNOME {gnome} is too old for Hanabi (needs {HANABI_MIN_GNOME}+)")
        branch = "javascript" if gnome <= HANABI_JS_MAX_GNOME else "main"
        desktop = os.environ.get("XDG_CURRENT_DESKTOP", "")
        if desktop and "GNOME" not in desktop.upper():
            self.warn(f"Your session reports desktop '{desktop}'; Hanabi only works in GNOME.")
        self.info(f"GNOME Shell {gnome}: using Hanabi's '{branch}' branch.")

        deps = list(HANABI_BUILD_DEPS) + (["nodejs", "npm"] if branch == "main" else [])
        self.apt_install(deps)
        media = [p for p in HANABI_MEDIA_DEPS if self.apt_has_candidate(p)]
        missing = sorted(set(HANABI_MEDIA_DEPS) - set(media))
        if missing:
            self.warn("Not available in apt, skipped: " + ", ".join(missing))
        if media:
            self.apt_install(media)

        src = Path(user.pw_dir) / ".cache" / "ps5-quick-setup" / "gnome-ext-hanabi"
        self.run_cmd(self.user_cmd(["mkdir", "-p", str(src.parent)]))
        self.run_cmd(self.user_cmd(["rm", "-rf", str(src)]))
        self.run_cmd(self.user_cmd(["git", "clone", "--depth", "1", "-b", branch,
                                    HANABI_REPO, str(src)]))
        self.run_cmd(self.user_cmd(["make", "install"]), cwd=src)

        dest_dir = Path(user.pw_dir) / ".local" / "share" / "backgrounds" / "ps5-quick-setup"
        try:
            self.make_user_dirs(dest_dir)
            dest = dest_dir / source.name
            if not (dest.exists() and dest.samefile(source)):
                shutil.copyfile(source, dest)
            os.chown(dest, user.pw_uid, user.pw_gid)
            dest.chmod(0o644)
        except OSError as exc:
            raise StepError(f"could not copy the wallpaper: {exc}") from exc
        self.ok(f"Wallpaper video: {dest}")

        schemadir = str(Path(user.pw_dir) / ".local" / "share" / "glib-2.0" / "schemas")
        for key, value in (("video-path", str(dest)), ("mute", "true")):
            self.run_cmd(self.user_cmd(
                ["gsettings", "--schemadir", schemadir, "set", HANABI_SCHEMA, key, value],
                session_bus=True,
            ))

        self._enable_gnome_extension(HANABI_UUID)
        return "ok", f"Hanabi installed with {dest.name}; log out and back in to see it"

    def _enable_gnome_extension(self, uuid: str) -> None:
        def read_list(key: str) -> list[str]:
            cmd = self.user_cmd(["gsettings", "get", "org.gnome.shell", key], session_bus=True)
            out = self.capture(cmd).strip()
            if out.startswith("@as"):
                out = out[3:].strip()
            try:
                value = ast.literal_eval(out) if out else []
            except (ValueError, SyntaxError):
                raise StepError(f"unexpected value for org.gnome.shell {key}: {out!r}")
            return [str(v) for v in value]

        def write_list(key: str, values: list[str]) -> None:
            gvariant = "[" + ", ".join(repr(v) for v in values) + "]"
            self.run_cmd(self.user_cmd(["gsettings", "set", "org.gnome.shell", key, gvariant],
                                       session_bus=True))

        enabled = read_list("enabled-extensions")
        if uuid not in enabled:
            write_list("enabled-extensions", enabled + [uuid])
        disabled = read_list("disabled-extensions")
        if uuid in disabled:
            write_list("disabled-extensions", [v for v in disabled if v != uuid])

        if self.capture(self.user_cmd(["gsettings", "get", "org.gnome.shell",
                                       "disable-user-extensions"], session_bus=True)).strip() == "true":
            self.warn("User extensions were switched off in GNOME; switching them on.")
            self.run_cmd(self.user_cmd(["gsettings", "set", "org.gnome.shell",
                                        "disable-user-extensions", "false"], session_bus=True))
        self.ok(f"Enabled {uuid} for the next login.")


