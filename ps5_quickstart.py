    def _fit_to_options(self) -> None:
        panel = getattr(self, "options_widget", None)
        if panel is None:
            return
        panel.layout().activate()
        height = panel.sizeHint().height()
        previous, self._options_height = self._options_height, height
        if previous is None or height == previous:
            return
        target = self.height() + height - previous
        screen = self.screen()
        if screen is not None:
            target = min(target, screen.availableGeometry().height())
        self.resize(self.width(), max(target, self.minimumSizeHint().height()))

