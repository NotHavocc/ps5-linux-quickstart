    @staticmethod
    def _dualsense_input_present() -> bool:
        for uevent in Path("/sys/bus/hid/devices").glob("*/uevent"):
            try:
                text = uevent.read_text()
            except OSError:
                continue
            if re.search(r"^HID_ID=0005:0000054C:0000(0CE6|0DF2)$", text, re.MULTILINE | re.IGNORECASE):
                return True
        return False

    def _pair_dualsense(self) -> bool | None:
        title = "Pair your DualSense"
        if not self.ask_user(
            title,
            "Put the DualSense in pairing mode:\n\n"
            "Hold the Create button (left of the touchpad) and the PS button together "
            "until the light bar flashes quickly (twice a second).\n\n"
            "Press 'Start pairing' once it is flashing. Its old pairing is removed first.",
            "Start pairing", "Skip pairing",
        ):
            self.info("DualSense pairing skipped; the existing pairing was left as it is.")
            return None

        for address, name in self._dualsense_devices():
            self.info(f"Removing the old pairing of {name} ({address}).")
            self.run_cmd(["bluetoothctl", "remove", address], check=False)

        while True:
            problem = self._pair_dualsense_once()
            if problem is None:
                return True
            if not self.ask_user(
                title,
                f"{problem}\n\nPut the DualSense back in pairing mode (hold Create + PS until "
                "the light bar flashes quickly), then press 'Try again'.",
                "Try again", "Give up",
            ):
                return False

    def _pair_dualsense_once(self) -> str | None:
        self.info("Scanning for the DualSense for 30 seconds...")
        self.run_cmd(["bluetoothctl", "--timeout", "30", "scan", "on"], check=False)
        found = self._dualsense_devices()
        if not found:
            problem = ("No DualSense showed up while scanning. Check that the light bar was "
                       "flashing quickly (pairing mode), not slowly.")
            self.warn(problem)
            return problem

        address, name = found[0]
        self.info(f"Pairing {name} ({address}).")
        script = (
            "{ printf 'agent NoInputNoOutput\\ndefault-agent\\npairable on\\n'; sleep 2; "
            f"printf 'pair {address}\\n'; sleep 15; "
            f"printf 'trust {address}\\nconnect {address}\\n'; sleep 5; "
            "printf 'quit\\n'; } | bluetoothctl"
        )
        self.run_cmd(["sh", "-c", script], check=False)

        info = self.capture(["bluetoothctl", "info", address])
        if not re.search(r"^\s*Paired: yes", info, re.MULTILINE):
            problem = "Pairing failed."
            self.warn(problem)
            self.run_cmd(["bluetoothctl", "remove", address], check=False)
            return problem
        if re.search(r"^\s*Bonded: no", info, re.MULTILINE):
            problem = ("The controller paired but no bond was stored (Bonded: no), so "
                       "BlueZ ignores its input.")
            self.warn(problem)
            self.run_cmd(["bluetoothctl", "remove", address], check=False)
            return problem
        self.ok(f"{name} is paired and bonded.")

        for _ in range(10):
            if self._dualsense_input_present():
                self.ok(f"{name} is paired, bonded and working as an input device.")
                return None
            self.run_cmd(["sleep", "1"], check=False)
        problem = f"{name} paired, but no input device appeared within 10 seconds."
        self.warn(problem)
        self.run_cmd(["bluetoothctl", "remove", address], check=False)
        return problem

