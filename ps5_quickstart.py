class SetupWorker(QThread):
    log = pyqtSignal(str, str)
    step_changed = pyqtSignal(int, int, str)
    done = pyqtSignal(list, bool)
    prompt = pyqtSignal(str, str, str, str)

    def __init__(self, options: SetupOptions) -> None:
        super().__init__()
        self.opts = options
        self._proc: subprocess.Popen | None = None
        self._lock = threading.Lock()
        self._cancelled = threading.Event()
        self._apt_updated = False
        self._answer = False
        self._answered = threading.Event()

    def ask_user(self, title: str, text: str, accept: str, reject: str) -> bool:
        self._check_cancel()
        self._answered.clear()
        self.prompt.emit(title, text, accept, reject)
        self._answered.wait()
        self._check_cancel()
        return self._answer

    def answer(self, accepted: bool) -> None:
        self._answer = accepted
        self._answered.set()

    def cancel(self) -> None:
        self._cancelled.set()
        self._answered.set()
        with self._lock:
            proc = self._proc
        if proc is not None and proc.poll() is None:
            self._signal_group(proc, signal.SIGTERM)
            timer = threading.Timer(5.0, self._signal_group, args=(proc, signal.SIGKILL))
            timer.daemon = True
            timer.start()

    @staticmethod
    def _signal_group(proc: subprocess.Popen, sig: int) -> None:
        if proc.poll() is None:
            try:
                os.killpg(proc.pid, sig)
            except (ProcessLookupError, PermissionError):
                pass

    def _check_cancel(self) -> None:
        if self._cancelled.is_set():
            raise Cancelled()

    def info(self, msg: str) -> None:
        self.log.emit(msg, "info")

    def ok(self, msg: str) -> None:
        self.log.emit(msg, "ok")

    def warn(self, msg: str) -> None:
        self.log.emit(msg, "warn")

    def error(self, msg: str) -> None:
        self.log.emit(msg, "error")

    def _plan(self) -> list[tuple[str, callable]]:
        o = self.opts
        steps: list[tuple[str, callable]] = []
        if o.kernel_patches or o.wifi:
            steps.append(("Prerequisites (git, pciutils)", self.step_prerequisites))
        if o.kernel_patches:
            steps.append(("Kernel patching", self.step_kernel_patches))
        if o.wifi and not o.kernel_patches:
            steps.append(("MediaTek WiFi driver", self.step_wifi))
        if o.steam_install:
            steps.append(("Steam + gamescope installation", self.step_steam_install))
        if o.dualsense:
            steps.append(("DualSense over Bluetooth", self.step_dualsense))
        if o.gamepad_ui:
            steps.append(("Steam Deck UI launcher", self.step_gamepad_launcher))
        if o.steam_autostart:
            steps.append(("Steam autostart", self.step_autostart))
        if o.gaming_mode:
            steps.append(("Gaming Mode session", self.step_gaming_mode))
        if o.wallpaper_file:
            steps.append(("Live wallpaper", self.step_live_wallpaper))
        return steps

    def run(self) -> None:
        steps = self._plan()
        results: list[tuple[str, str, str]] = []
        total = len(steps)

        try:
            WORK_DIR.mkdir(parents=True, exist_ok=True)
            WORK_DIR.chmod(0o755)
        except OSError as exc:
            self.error(f"Cannot create work directory {WORK_DIR}: {exc}")

        for index, (title, func) in enumerate(steps):
            if self._cancelled.is_set():
                results.append((title, "cancelled", "not started"))
                continue
            self.step_changed.emit(index, total, title)
            self.log.emit(f"==== {title} ====", "section")
            try:
                status, detail = func()
                results.append((title, status, detail))
                level = {"ok": "ok", "manual": "warn", "skipped": "warn"}.get(status, "info")
                self.log.emit(f"{title}: {detail}", level)
            except Cancelled:
                self.warn(f"{title}: cancelled by user")
                results.append((title, "cancelled", "interrupted"))
            except StepError as exc:
                self.error(f"{title} failed: {exc}")
                results.append((title, "failed", str(exc)))
            except Exception as exc:
                self.error(f"{title} crashed: {exc!r}")
                for line in traceback.format_exc().splitlines():
                    self.log.emit(line, "error")
                results.append((title, "failed", repr(exc)))

        self.step_changed.emit(total, total, "Finished")
        self.done.emit(results, self._cancelled.is_set())

    def run_cmd(
        self,
        cmd: list[str],
        cwd: Path | None = None,
        check: bool = True,
        input_text: str | None = None,
        env_extra: dict[str, str] | None = None,
    ) -> int:
        self._check_cancel()
        prefix = f"[{cwd}] " if cwd else ""
        self.log.emit(f"{prefix}$ {shlex.join(cmd)}", "cmd")

        env = os.environ.copy()
        env.update(
            PATH=SAFE_PATH,
            DEBIAN_FRONTEND="noninteractive",
            GIT_TERMINAL_PROMPT="0",
            PAGER="cat",
            SYSTEMD_PAGER="cat",
            TERM="dumb",
        )
        if env_extra:
            env.update(env_extra)
            self.info("  with " + " ".join(f"{k}={v}" for k, v in env_extra.items()))
        try:
            proc = subprocess.Popen(
                cmd,
                cwd=str(cwd) if cwd else None,
                env=env,
                stdin=subprocess.PIPE if input_text is not None else subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                errors="replace",
                bufsize=1,
                start_new_session=True,
            )
        except FileNotFoundError as exc:
            raise StepError(f"command not found: {cmd[0]}") from exc
        except OSError as exc:
            raise StepError(f"could not start {cmd[0]}: {exc}") from exc

        with self._lock:
            self._proc = proc
        try:
            if input_text is not None:
                proc.stdin.write(input_text)
                proc.stdin.close()
            for line in proc.stdout:
                line = line.rstrip()
                if line:
                    self.log.emit(line, "out")
            rc = proc.wait()
        finally:
            with self._lock:
                self._proc = None

        if self._cancelled.is_set():
            raise Cancelled()
        if rc != 0:
            msg = f"{Path(cmd[0]).name} exited with status {rc}"
            if check:
                raise StepError(msg)
            self.warn(msg + " (continuing)")
        return rc

    @staticmethod
    def capture(cmd: list[str]) -> str:
        try:
            return subprocess.run(
                cmd, capture_output=True, text=True, timeout=60,
                env={**os.environ, "PATH": SAFE_PATH, "LC_ALL": "C"},
            ).stdout
        except (OSError, subprocess.SubprocessError):
            return ""

    def apt_update(self, force: bool = False) -> None:
        if self._apt_updated and not force:
            return
        self.run_cmd(["apt-get", "update", "-o", "DPkg::Lock::Timeout=300"])
        self._apt_updated = True

    def apt_install(self, packages: list[str], check: bool = True) -> int:
        self.apt_update()
        return self.run_cmd(["apt-get", "install", *APT_OPTS, *packages], check=check)

    def apt_has_candidate(self, package: str) -> bool:
        out = self.capture(["apt-cache", "policy", package])
        match = re.search(r"Candidate:\s*(\S+)", out)
        return bool(match) and match.group(1) != "(none)"

    def clone_or_update(self, url: str, dest: Path) -> Path:
        dest = dest.resolve()
        if WORK_DIR.resolve() not in dest.parents:
            raise StepError(f"refusing to manage repository outside {WORK_DIR}: {dest}")

        if (dest / ".git").is_dir():
            self.info(f"Updating existing clone in {dest}")
            if self.run_cmd(["git", "-C", str(dest), "pull", "--ff-only"], check=False) == 0:
                return dest
            self.warn("Update failed; re-cloning from scratch.")
        if dest.exists():
            shutil.rmtree(dest)

        self.run_cmd(["git", "clone", "--depth", "1", url, str(dest)])
        head = self.capture(["git", "-C", str(dest), "log", "-1", "--format=%h %s (%cd)"]).strip()
        if head:
            self.info(f"Checked out: {head}")
        return dest

    @staticmethod
    def find_script(repo: Path, names: tuple[str, ...], max_depth: int = 2) -> Path | None:
        for name in names:
            candidate = repo / name
            if candidate.is_file():
                return candidate
        for name in names:
            for candidate in sorted(repo.rglob(name)):
                rel = candidate.relative_to(repo)
                if ".git" in rel.parts or len(rel.parts) > max_depth + 1:
                    continue
                if candidate.is_file():
                    return candidate
        return None

    def run_repo_script(self, script: Path, args: list[str] | None = None) -> None:
        if not script.is_file():
            raise StepError(f"{script} not found")
        cmd = [str(script)] if os.access(script, os.X_OK) else ["bash", str(script)]
        self.run_cmd(cmd + (args or []), cwd=script.parent)

    def user_cmd(self, cmd: list[str], session_bus: bool = False) -> list[str]:
        user = self.opts.user
        env = [f"HOME={user.pw_dir}", f"USER={user.pw_name}",
               f"LOGNAME={user.pw_name}", f"PATH={SAFE_PATH}"]
        if session_bus:
            runtime_dir = f"/run/user/{user.pw_uid}"
            if Path(runtime_dir, "bus").exists():
                env += [f"XDG_RUNTIME_DIR={runtime_dir}",
                        f"DBUS_SESSION_BUS_ADDRESS=unix:path={runtime_dir}/bus"]
            else:
                cmd = ["dbus-run-session", "--", *cmd]
        return ["runuser", "-u", user.pw_name, "--", "env", *env, *cmd]

    def install_sudoers_rule(self, path: Path, rule: str) -> None:
        staging = path.with_name(path.name + ".new")
        try:
            path.parent.mkdir(mode=0o750, parents=True, exist_ok=True)
            staging.write_text(f"# {GENERATED_MARKER}.\n{rule}")
            staging.chmod(0o440)
            if self.run_cmd(["visudo", "-cf", str(staging)], check=False) != 0:
                raise StepError(f"visudo rejected the sudoers rule for {path}")
            os.replace(staging, path)
        except OSError as exc:
            raise StepError(f"could not install {path}: {exc}") from exc
        finally:
            staging.unlink(missing_ok=True)
        self.ok(f"Wrote {path}")

    def make_user_dirs(self, path: Path) -> None:
        uid, gid = self.opts.user.pw_uid, self.opts.user.pw_gid
        missing = []
        current = path
        while not current.exists():
            missing.append(current)
            current = current.parent
        for directory in reversed(missing):
            directory.mkdir(mode=0o755)
            os.chown(directory, uid, gid)

    def write_file(self, path: Path, content: str, mode: int, owned_by_user: bool = False) -> None:
        try:
            path.write_text(content)
            path.chmod(mode)
            if owned_by_user:
                os.chown(path, self.opts.user.pw_uid, self.opts.user.pw_gid)
        except OSError as exc:
            raise StepError(f"could not write {path}: {exc}") from exc
        self.ok(f"Wrote {path}")

    def write_generated_file(self, path: Path, content: str, mode: int) -> None:
        assert GENERATED_MARKER in content, path
        if path.exists():
            try:
                current = path.read_text(errors="replace")
            except OSError:
                current = ""
            if GENERATED_MARKER not in current:
                raise StepError(f"{path} already exists and was not created by {APP_NAME}; "
                                "not overwriting it")
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            raise StepError(f"could not create {path.parent}: {exc}") from exc
        self.write_file(path, content, mode)

