def led_swatch(levels: tuple[int, int, int] | None) -> QIcon:
    from PyQt6.QtGui import QPainter

    size, bar = 16, 4
    pixmap = QPixmap(size, size)
    pixmap.fill(Qt.GlobalColor.transparent)
    if levels is None:
        return QIcon(pixmap)
    painter = QPainter(pixmap)
    painter.setPen(QColor("#888888"))
    painter.drawRect(0, 0, size - 1, size - 1)
    colours = (QColor("#2f6bff"), QColor("#a8a8a8"), QColor("#ff8a1f"))
    for i, (level, colour) in enumerate(zip(levels, colours)):
        height = 0 if level == 0 else max(2, round((size - 4) * level / 255))
        painter.fillRect(2 + i * (bar + 1), size - 2 - height, bar, height, colour)
    painter.end()
    return QIcon(pixmap)


