    def _set_bluez_conf(self, path: Path, section: str, keys: dict[str, str],
                        what: str) -> bool:
        setting = ", ".join(f"{k}={v}" for k, v in keys.items())
        try:
            text = path.read_text() if path.exists() else ""
            new = set_ini_keys(text, section, keys)
            if new == text:
                self.info(f"{what}: already set ({setting}).")
                return False
            backup = path.with_name(path.name + ".ps5-quickstart.bak")
            if path.exists() and not backup.exists():
                shutil.copy2(path, backup)
                self.info(f"Backed up {path} to {backup}")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(new)
        except OSError as exc:
            raise StepError(f"could not update {path}: {exc}") from exc
        self.ok(f"{what}: {setting} in {path}.")
        return True

    @staticmethod
    def _bluetooth_usb_ids() -> list[tuple[str, str]]:
        ids: list[tuple[str, str]] = []
        for hci in SYS_BLUETOOTH.glob("hci*"):
            device = (hci / "device").resolve()
            for candidate in (device, device.parent):
                vendor, product = candidate / "idVendor", candidate / "idProduct"
                if vendor.is_file() and product.is_file():
                    pair = (vendor.read_text().strip(), product.read_text().strip())
                    if pair not in ids:
                        ids.append(pair)
                    break
        return ids

    def _disable_bluetooth_autosuspend(self) -> None:
        devices = [("054c", "0ce6"), ("054c", "0df2")]
        adapters = self._bluetooth_usb_ids()
        if adapters:
            self.info("Bluetooth adapter(s): " + ", ".join(f"{v}:{p}" for v, p in adapters))
        else:
            self.warn("No USB Bluetooth adapter found in /sys/class/bluetooth.")
        rules = "".join(
            f'ACTION=="add", SUBSYSTEM=="usb", ATTR{{idVendor}}=="{v}", '
            f'ATTR{{idProduct}}=="{p}", ATTR{{power/control}}="on"\n'
            for v, p in devices + adapters
        )
        self.write_generated_file(
            BT_POWER_UDEV_RULES,
            f"# {GENERATED_MARKER}: no USB autosuspend for the Bluetooth adapter\n"
            "# and DualSense controllers (it drops Bluetooth connections).\n" + rules,
            0o644,
        )
        self.write_generated_file(
            BTUSB_MODPROBE_CONF,
            f"# {GENERATED_MARKER}: no USB autosuspend for Bluetooth adapters.\n"
            "options btusb enable_autosuspend=n\n",
            0o644,
        )
        for hci in SYS_BLUETOOTH.glob("hci*"):
            device = (hci / "device").resolve()
            for candidate in (device, device.parent):
                control = candidate / "power" / "control"
                if (candidate / "idVendor").is_file() and control.is_file():
                    try:
                        control.write_text("on")
                        self.ok(f"USB autosuspend off for {candidate.name} now.")
                    except OSError as exc:
                        self.warn(f"Could not turn off autosuspend for {candidate.name}: {exc}")
                    break

    def _trust_paired_dualsense(self) -> int:
        controllers = self._dualsense_devices("Paired")
        if not controllers:
            self.info("No paired DualSense yet. After pairing one, run this step again "
                      "(or `bluetoothctl trust <address>`) so the PS button reconnects it.")
        for address, name in controllers:
            self.run_cmd(["bluetoothctl", "trust", address], check=False)
            self.ok(f"Trusted {name} ({address}).")
        return len(controllers)

